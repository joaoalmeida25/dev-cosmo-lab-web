import { getImageProps } from 'next/image';
import type { IArtworkStyle } from './themed-artwork.types';
import { ThemedArtworkView } from './themed-artwork-view.component';

interface IThemedArtworkProps {
  darkSrc: string;
  lightSrc: string;
  mobileDarkSrc?: string;
  mobileLightSrc?: string;
  width: number;
  height: number;
  lightWidth?: number;
  lightHeight?: number;
  alt?: string;
  className?: string;
}

const getImageSet = (src: string, width: number, height: number) => {
  const { props } = getImageProps({ src, width, height, alt: '', quality: 75 });

  return `image-set(${props.srcSet
    ?.split(', ')
    .map((candidate) => {
      const [url, density] = candidate.split(' ');
      return `url("${url}") ${density}`;
    })
    .join(', ')})`;
};

// Load only after the theme initializer has selected the persisted preference.
// Inline custom properties are limited to the URLs generated by Next's image loader.
export const ThemedArtwork = ({
  darkSrc,
  lightSrc,
  mobileDarkSrc,
  mobileLightSrc,
  width,
  height,
  lightWidth = width,
  lightHeight = height,
  alt,
  className = '',
}: IThemedArtworkProps) => {
  const style: IArtworkStyle = {
    '--artwork-dark': getImageSet(darkSrc, width, height),
    '--artwork-light': getImageSet(lightSrc, lightWidth, lightHeight),
    '--artwork-mobile-dark': mobileDarkSrc ? getImageSet(mobileDarkSrc, 753, 941) : undefined,
    '--artwork-mobile-light': mobileLightSrc ? getImageSet(mobileLightSrc, 753, 941) : undefined,
  };

  return (
    <ThemedArtworkView
      artworkStyle={style}
      alt={alt}
      className={className}
      hasMobileArtwork={Boolean(mobileDarkSrc)}
    />
  );
};
